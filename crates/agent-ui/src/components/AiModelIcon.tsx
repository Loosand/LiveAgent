function InlineBrandMark({ brand }: { brand: ModelIconBrand }) {
  const className = "size-3.5 shrink-0";
  if (brand === "claude") return <ClaudeIcon className={className} />;
  if (brand === "deepseek") return <DeepseekIcon className={className} />;
  if (brand === "gemini") return <GeminiIcon className={className} />;
  if (brand === "grok") return <GrokIcon className={className} />;
  if (brand === "openai") {
    return <OpenaiChatgptIcon className={cn(className, "fill-current dark:text-white")} />;
  }

  const paths = MODEL_BRAND_PATHS[brand];
  if (!paths) return <Sparkles className={className} />;
  return (
    <svg className={className} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      {paths.map((path) => (
        <path key={path} d={path} />
      ))}
    </svg>
  );
}

export function AiModelIcon({
  modelId,
  providerType,
  className,
}: {
  modelId: string;
  providerType?: string;
  className?: string;
}) {
  const brand = resolveModelIconBrand(modelId, providerType);
  return (
    <span
      aria-hidden="true"
      className={cn(
        "inline-flex size-5 shrink-0 items-center justify-center rounded-[5px]",
        brand ? MODEL_BRAND_COLORS[brand] : "bg-muted/70 text-muted-foreground",
        className,
      )}
    >
      {brand ? <InlineBrandMark brand={brand} /> : <Sparkles className="size-3.5" />}
    </span>
  );
}
